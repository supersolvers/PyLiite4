"""Compile a .gresource.xml file to a Python module.

Import the generated module once to register its resources with GIO. Then
Gtk.Template(resource_path=...), Gtk.Builder.new_from_resource() and
Gio.File.new_for_uri("resource://...") find them.
"""

import argparse
import base64
import shutil
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

import PyLiite4  # noqa: F401  (puts bundled tools on PATH)

TEMPLATE = '''"""Generated by pyliite4-resources. Do not edit."""

import base64

from PyLiite4 import Gio, GLib

_DATA = """
{data}
"""

Gio.resources_register(Gio.Resource.new_from_data(GLib.Bytes.new(base64.b64decode(_DATA))))
'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="pyliite4-resources", description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("-o", "--output", type=Path, help="output file (default: stdout)")
    args = parser.parse_args(argv)
    compiler = shutil.which("glib-compile-resources")
    if compiler is None:
        print("pyliite4-resources: glib-compile-resources was not found", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as directory:
        target = Path(directory) / "resources.gresource"
        result = subprocess.run([compiler, f"--target={target}", f"--sourcedir={args.input.parent}", str(args.input)])
        if result.returncode:
            return result.returncode
        data = base64.b64encode(target.read_bytes()).decode()
    code = TEMPLATE.format(data=textwrap.fill(data, 100))
    if args.output:
        args.output.write_text(code)
    else:
        sys.stdout.write(code)
    return 0


if __name__ == "__main__":
    sys.exit(main())
