"""Generate typed Python for a GtkBuilder .ui file.

A file with a <template> defines a composite widget. It becomes a mixin that
types the template's children, and a ``template`` decorator that applies
``Gtk.Template`` to your class:

    @template
    class ExampleWindow(ExampleWindowChildren, Adw.ApplicationWindow):
        __gtype_name__ = "ExampleWindow"

        def on_save_clicked(self, button: Gtk.Button) -> None: ...

The decorator binds every object with an id and every signal handler and
expression closure that the file names, and fails at import if the class has
the wrong parent, name or handlers. The template is embedded in the module, or
with --resource loaded from that GResource path, as Gtk.Template(resource_path=)
does.

Any other file becomes a class that builds its objects with ``Gtk.Builder``
and has one typed attribute per object id.
"""

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

PREFIXES = (("Gtk", "Gtk"), ("Adw", "Adw"), ("Gio", "Gio"), ("Gdk", "Gdk"))


def python_type(gtype: str) -> tuple[str, str]:
    for prefix, module in PREFIXES:
        if gtype.startswith(prefix) and gtype[len(prefix):len(prefix) + 1].isupper():
            return f"{module}.{gtype[len(prefix):]}", module
    return "GObject.Object", "GObject"


def attribute_name(object_id: str) -> str:
    attribute = re.sub(r"\W", "_", object_id)
    return attribute if attribute.isidentifier() else f"_{attribute}"


def objects(element: ET.Element, reserved: set[str]) -> list[tuple[str, str, str]]:
    """(id, attribute, annotation) for every object with an id, in file order."""
    found, seen = [], set(reserved)
    for child in element.iter("object"):
        object_id, gtype = child.get("id"), child.get("class")
        if not object_id or not gtype:
            continue
        attribute = attribute_name(object_id)
        if attribute in seen:
            raise ValueError(f"object id {object_id!r} clashes with another name")
        seen.add(attribute)
        found.append((object_id, attribute, python_type(gtype)[0]))
    return found


def camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"\W|_", name) if part)


def module_header(source_name: str, modules: set[str], source: str | None) -> list[str]:
    lines = [f'"""Generated by pyliite4-ui from {source_name}. Do not edit."""', "",
             "from typing import Any, TypeVar, cast", "",
             f"from PyLiite4 import {', '.join(sorted(modules | {'Gtk'}))}", ""]
    return lines + ([f"_UI = {source!r}", ""] if source is not None else [])


def compile_template(root: ET.Element, template: ET.Element, source: str, source_name: str,
                     resource: str | None = None) -> str:
    gtype_name, parent = template.get("class"), template.get("parent")
    if not gtype_name or not parent:
        raise ValueError("<template> needs class and parent attributes")
    parent_type, parent_module = python_type(parent)
    # GTK binds any object in the file by id, not just those inside <template>.
    children = objects(root, {"template"})
    handlers = sorted({s.get("handler") for s in root.iter("signal") if s.get("handler")} |
                      {c.get("function") for c in root.iter("closure") if c.get("function")})
    for handler in handlers:
        if not handler.isidentifier():
            raise ValueError(f"handler {handler!r} isn't a Python identifier")
    modules = {parent_module, "GObject"} | {annotation.split(".")[0] for _, _, annotation in children}
    children_class = f"{gtype_name}Children"
    lines = module_header(source_name, modules, None if resource else source)
    lines += ["_W = TypeVar('_W', bound=type[Gtk.Widget])", "",
              *([f"RESOURCE = {resource!r}"] if resource else []),
              f"CLASS_NAME = {gtype_name!r}",
              f"PARENT = {parent_type}",
              f"CHILDREN = {tuple((object_id, attribute) for object_id, attribute, _ in children)!r}",
              f"HANDLERS = {tuple(handlers)!r}", "", "",
              f"class {children_class}:",
              f'    """The children of the {gtype_name} template, as attributes."""', ""]
    lines += [f"    {attribute}: {annotation}" for _, attribute, annotation in children] or ["    pass"]
    lines += ["", "",
              "def template(cls: _W) -> _W:",
              f'    """Make ``cls`` the {gtype_name} widget defined by {source_name}."""',
              "    if cls.__dict__.get('__gtype_name__') != CLASS_NAME:",
              "        raise TypeError(f'{cls.__name__} must set __gtype_name__ = {CLASS_NAME!r}')",
              "    if not issubclass(cls, PARENT):",
              "        raise TypeError(f'{cls.__name__} must be a subclass of {PARENT.__qualname__}')",
              "    missing = [name for name in HANDLERS if not callable(getattr(cls, name, None))]",
              "    if missing:",
              "        raise TypeError(f'{cls.__name__} lacks the signal handlers {\", \".join(missing)}')",
              "    for object_id, attribute in CHILDREN:",
              "        setattr(cls, attribute, Gtk.Template.Child(object_id))",
              "    for name in HANDLERS:",
              "        setattr(cls, name, Gtk.Template.Callback(name)(getattr(cls, name)))",
              f"    return Gtk.Template({'resource_path=RESOURCE' if resource else 'string=_UI'})(cls)", ""]
    return "\n".join(lines)


def compile_objects(root: ET.Element, source: str, source_name: str, class_name: str) -> str:
    found = objects(root, {"builder"})
    modules = {annotation.split(".")[0] for _, _, annotation in found}
    lines = module_header(source_name, modules, source)
    lines += ["", f"class {class_name}:",
              f'    """The objects of {source_name}.',
              "",
              "    ``handlers`` is an object or mapping whose attributes or keys are the",
              "    signal handlers that the file names.",
              '    """', "",
              "    def __init__(self, handlers: Any = None) -> None:",
              "        self.builder = Gtk.Builder(handlers)",
              "        self.builder.add_from_string(_UI)"]
    lines += [f"        self.{attribute} = cast({annotation}, self.builder.get_object({object_id!r}))"
              for object_id, attribute, annotation in found]
    return "\n".join(lines + [""])


def compile_ui(source: str, source_name: str = "the .ui file", class_name: str | None = None,
               resource: str | None = None) -> str:
    root = ET.fromstring(source)
    if root.tag != "interface":
        raise ValueError("the root element must be <interface>")
    templates = root.findall("template")
    if len(templates) > 1:
        raise ValueError("a file can define only one <template>")
    if templates:
        return compile_template(root, templates[0], source, source_name, resource)
    if resource:
        raise ValueError("--resource only applies to a file with a <template>")
    return compile_objects(root, source, source_name, class_name or f"{camel(Path(source_name).stem)}Objects")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="pyliite4-ui", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", type=Path)
    parser.add_argument("-o", "--output", type=Path, help="output file (default: stdout)")
    parser.add_argument("--class-name", help="class for a file without a template (default: <File>Objects)")
    parser.add_argument("--resource", metavar="PATH",
                        help="load the template from this GResource path instead of embedding it")
    args = parser.parse_args(argv)
    try:
        code = compile_ui(args.input.read_text(), args.input.name, args.class_name, args.resource)
    except (OSError, ET.ParseError, ValueError) as error:
        print(f"pyliite4-ui: {args.input}: {error}", file=sys.stderr)
        return 1
    if args.output:
        args.output.write_text(code)
    else:
        sys.stdout.write(code)
    return 0


if __name__ == "__main__":
    sys.exit(main())
