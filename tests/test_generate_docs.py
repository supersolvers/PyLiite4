"""The stubs carry GTK's documentation, converted from C to the Python names PyGObject exposes."""

import ast
import importlib.util
import re
from functools import cache
from pathlib import Path

import pytest

PACKAGE = Path(importlib.util.find_spec("PyLiite4").origin).parent
# cairo.pyi is written by hand.
STUBS = sorted(path for path in PACKAGE.glob("*.pyi") if path.stem != "cairo")


@cache
def tree(namespace):
    return ast.parse((PACKAGE / f"{namespace}.pyi").read_text())


def member(namespace, path):
    """The class or function at a dotted path such as Button.new_with_label, by its first definition."""
    node = tree(namespace)
    for name in path.split("."):
        node = next(n for n in node.body if isinstance(n, (ast.ClassDef, ast.FunctionDef)) and n.name == name)
    return node


def docstrings(path):
    for node in ast.walk(ast.parse(path.read_text())):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef)) and ast.get_docstring(node):
            yield node, ast.get_docstring(node)


def prose(text):
    """Text outside code, where C syntax should have been converted."""
    return re.sub(r"`[^`\n]*`", "", re.sub(r"```.*?```", "", text, flags=re.S))


@pytest.mark.parametrize("path", STUBS, ids=lambda path: path.stem)
def test_module_docstring_names_the_library(path):
    text = ast.get_docstring(ast.parse(path.read_text()))
    assert text and "Generated by tools/generate.py" in text


def test_classes_and_methods_have_gtk_docs():
    assert ast.get_docstring(member("Gtk", "Button")).startswith("Calls a callback function when the button is clicked.")
    text = ast.get_docstring(member("Gtk", "Button.new_with_label"))
    assert "Args:\n    label: " in text and "Returns:\n    " in text
    assert ast.get_docstring(member("Adw", "ApplicationWindow"))


def test_deprecations_are_noted():
    assert "Deprecated since 4.10" in ast.get_docstring(member("Gtk", "Widget.show"))


def test_c_names_become_python_names():
    text = ast.get_docstring(member("Gtk", "Button"))
    assert "`Gtk.Widget`" in text and "GtkWidget" not in text


def test_parameters_python_doesnt_pass_are_not_documented():
    text = ast.get_docstring(member("Gtk", "ListBox.set_filter_func"))
    assert "filter_func:" in text
    assert "user_data" not in text and "destroy" not in text


@pytest.mark.parametrize("path", STUBS, ids=lambda path: path.stem)
def test_markup_is_converted(path):
    for node, text in docstrings(path):
        where = f"{path.stem}.{getattr(node, 'name', '')}"
        assert "\0" not in text, where
        assert "|[" not in text, where
        # Well-formed gi-docgen links such as [class@Gtk.Button]; upstream has a few malformed ones.
        assert not re.search(r"\[\w+@[\w.:-]+\]", prose(text)), where
        assert not re.search(r"%(TRUE|FALSE|NULL)\b", prose(text)), where
